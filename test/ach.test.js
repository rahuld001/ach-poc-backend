import test from 'node:test';
import assert from 'node:assert/strict';
import {
  authorizationText, federalReserveHolidays, isBankingDay, nextBusinessDay, toIsoDate,
} from '../src/ach.js';

const iso = (d) => toIsoDate(d);

test('Federal Reserve holidays for 2026', () => {
  const days = federalReserveHolidays(2026).map(iso);
  assert.deepEqual(days, [
    '2026-01-01', // New Year's Day (Thursday)
    '2026-01-19', // MLK Day: third Monday of January
    '2026-02-16', // Presidents' Day: third Monday of February
    '2026-05-25', // Memorial Day: last Monday of May
    '2026-06-19', // Juneteenth (Friday)
    '2026-07-04', // Independence Day falls on a Saturday: not moved, the Fed is open Friday 3 July
    '2026-09-07', // Labor Day: first Monday of September
    '2026-10-12', // Columbus Day: second Monday of October
    '2026-11-11', // Veterans Day (Wednesday)
    '2026-11-26', // Thanksgiving: fourth Thursday of November
    '2026-12-25', // Christmas (Friday)
  ]);
});

test('Sunday holidays are observed on the Monday', () => {
  // 4 July 2027 is a Sunday, so Monday 5 July is the holiday.
  assert.ok(federalReserveHolidays(2027).map(iso).includes('2027-07-05'));
  assert.ok(!isBankingDay(new Date(2027, 6, 5)));
});

test('banking days skip weekends and holidays', () => {
  assert.ok(isBankingDay(new Date(2026, 6, 3))); // Friday before a Saturday 4 July: open
  assert.ok(!isBankingDay(new Date(2026, 10, 26))); // Thanksgiving
  assert.ok(!isBankingDay(new Date(2026, 9, 10))); // Saturday
});

test('next business day skips weekends and holidays', () => {
  assert.equal(iso(nextBusinessDay(new Date(2026, 9, 2))), '2026-10-05'); // Fri -> Mon
  assert.equal(iso(nextBusinessDay(new Date(2026, 9, 5))), '2026-10-06'); // Mon -> Tue
  // Monday 12 Oct 2026 is Columbus Day, so the day after Friday 9 Oct is Tuesday 13 Oct.
  assert.equal(iso(nextBusinessDay(new Date(2026, 9, 9))), '2026-10-13');
  // Wednesday 25 Nov 2026 -> Thanksgiving skipped -> Friday 27 Nov.
  assert.equal(iso(nextBusinessDay(new Date(2026, 10, 25))), '2026-11-27');
  // Thursday 24 Dec 2026 -> Christmas (Fri) and the weekend skipped -> Monday 28 Dec.
  assert.equal(iso(nextBusinessDay(new Date(2026, 11, 24))), '2026-12-28');
});

test('authorization text is generated by the server from the payment details', () => {
  const debit = authorizationText('debit', 123456, '4321');
  assert.match(debit, /debit my bank account ending in 4321 for \$1,234\.56/);
  assert.match(debit, /credit my account to correct erroneous debits/);
  const credit = authorizationText('credit', 999, '0001');
  assert.match(credit, /credit \$9\.99 to my bank account ending in 0001/);
  assert.ok(!credit.includes('{'), 'all placeholders filled');
});
